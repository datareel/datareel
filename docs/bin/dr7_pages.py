def fn_id(sig):
    m = re.search(r'(\w+)::(~?\w+)\s*\(', sig) or re.search(r'(\w+)\s*\(', sig)
    if not m: return re.sub(r'\W+', '_', sig)[:40]
    name = m.group(m.lastindex)
    return name.replace('~', 'Destructor')

def render(p):
    head = HEAD.format(title=html.escape(p['title']))
    if p['file'].count('/') == 1:
        head = head.replace('../../', '../')
        sect = p['file'].split('/')[0]
        head = head.replace(' aria-current="page"', '')
        head = head.replace('href="../%s/%s.htm"' % (sect, sect if sect != 'examples' else 'examples'),
                            'href="../%s/%s.htm" aria-current="page"' % (sect, sect if sect != 'examples' else 'examples'))
    out = [head]
    out.append('<H1>%s</H1>\n' % html.escape(p['title']))
    if p.get('lead'):
        out.append('<p class="dr-lead">%s</p>\n' % p['lead'])
    secs = p.get('sections', [])
    fns = p.get('functions', [])
    out.append('<div class="dr-toc-title">Contents</div>\n<P class="dr-toc">')
    toc = ['<A HREF="#%s">%s</A>' % (s[0], html.escape(s[1])) for s in secs]
    for g in fns:
        toc.append('<A HREF="#%s">%s</A>' % (g[0], html.escape(g[1])))
    out.append('<BR>\n'.join(toc) + '</P>\n\n')
    for sid, heading, body in secs:
        out.append('<h2 id="%s">%s</h2>\n%s\n\n' % (sid, html.escape(heading), body.strip()))
    used = set()
    for gid, heading, items in fns:
        out.append('<h2 id="%s">%s</h2>\n' % (gid, html.escape(heading)))
        for sig, desc in items:
            i = fn_id(sig); base = i; n = 2
            while i in used: i = '%s%d' % (base, n); n += 1
            used.add(i)
            out.append('<div class="dr-fn" id="%s"><code class="dr-sig">%s</code>'
                       '<p class="dr-desc">%s</p></div>\n' % (i, html.escape(sig), desc))
        out.append('\n')
    out.append(FOOT.format(version=VERSION))
    return ''.join(out)

def code(s):
    return '<PRE>' + html.escape(s.strip('\n')) + '</PRE>'

